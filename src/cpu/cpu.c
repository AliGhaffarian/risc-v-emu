int write_mem(
    struct rv64_cpu *_Nonnull cpu,
    uint64_t address,
    uint64_t length,
    uint64_t write)
{
    assert(cpu);

    assert(length <= 8);

    uint64_t current_fetch = 0;

    for(int i = 0; i < length; i++) {
        // NOLINTNEXTLINE(readability-magic-numbers)
        cpu->mem[(address + i) % (cpu->opt.mem_size)] = write & 0xff;
        // NOLINTNEXTLINE(readability-magic-numbers)
        write >>= 8;
    }

    return 0;
}

