int read_mem(
    struct rv64_cpu *_Nonnull cpu,
    uint64_t address,
    uint64_t *_Nonnull ret,
    uint64_t length)
{
    assert(ret);
    assert(cpu);

    assert(length <= 8);

    uint64_t current_fetch = 0;

    (*ret) = 0;

    for(int i = 0; i < length; i++) {
        current_fetch = cpu->mem[(address + i) % (cpu->opt.mem_size)];
        // NOLINTNEXTLINE(readability-magic-numbers)
        current_fetch <<= (i * 8);
        *ret |= current_fetch;
    }

    return 0;
}

